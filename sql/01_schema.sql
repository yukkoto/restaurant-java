-- Выполнить в базе restaurant. Повторный запуск не удаляет существующие данные.
CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    phone VARCHAR(12) NOT NULL UNIQUE CHECK (phone ~ '^[+][7][0-9]{10}$')
);
CREATE TABLE IF NOT EXISTS restaurant_orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    table_number INTEGER NOT NULL CHECK (table_number BETWEEN 1 AND 20),
    description VARCHAR(500) NOT NULL CHECK (length(trim(description)) > 0),
    total NUMERIC(10,2) NOT NULL CHECK (total > 0 AND total <= 99999999.99),
    status VARCHAR(20) NOT NULL DEFAULT 'NEW'
        CHECK (status IN ('NEW', 'COOKING', 'SERVED', 'PAID', 'CANCELLED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
